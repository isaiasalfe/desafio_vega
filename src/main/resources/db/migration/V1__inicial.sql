create table tipo_ingrediente (
    id bigint generated by default as identity primary key,
    dt_cadastro timestamp(6) not null,
    nome varchar(20) not null,
    capacidade float(53) not null,
    unidade varchar(5) not null
);

create table compartimento (
    id bigint generated by default as identity primary key,
    dt_cadastro timestamp(6) not null,
    nome varchar(255) not null,
    id_tipo_ingrediente_atual bigint,
    quantidade_armazenada float(53),
    quantidade_disponivel float(53),
    capacidade_atual float(53),
    dt_ultimo_esvaziamento timestamp(6),
    constraint fk_compartimento_tipo_ingrediente
        foreign key (id_tipo_ingrediente_atual) references tipo_ingrediente (id)
);

create table ingrediente (
    id bigint generated by default as identity primary key,
    dt_cadastro timestamp(6) not null,
    nome varchar(255) not null,
    id_tipo_ingrediente bigint not null,
    id_compartimento bigint not null,
    quantidade_entrada float(53) not null,
    quantidade_disponivel float(53) not null,
    fl_ativo boolean not null,
    constraint fk_ingrediente_tipo_ingrediente
        foreign key (id_tipo_ingrediente) references tipo_ingrediente (id),
    constraint fk_ingrediente_compartimento
        foreign key (id_compartimento) references compartimento (id)
);

create table operacao (
    id bigint generated by default as identity primary key,
    dt_cadastro timestamp(6) not null,
    tipo_operacao varchar(20) not null,
    quantidade float(53) not null,
    id_ingrediente bigint not null,
    id_compartimento bigint not null,
    nome_responsavel varchar(255) not null,
    constraint fk_operacao_ingrediente
        foreign key (id_ingrediente) references ingrediente (id),
    constraint fk_operacao_compartimento
        foreign key (id_compartimento) references compartimento (id)
);
